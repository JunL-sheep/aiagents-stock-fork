def stocks_for_sector(sector_key):
    """取一个板块的所有股票 [(code, name, weight), ...]"""
    return SECTOR_STOCK_MAP.get(sector_key, [])


def find_sectors_by_keyword(text):
    """
    在一段文本中识别板块，返回 [(sector_key, [(code, name, weight), ...]), ...]
    去重 + 保留原始顺序
    """
    if not text:
        return []
    text_lower = text.lower()
    seen = set()
    result = []
    for kw, sector in KEYWORD_TO_SECTOR.items():
        if kw in text_lower and sector not in seen:
            seen.add(sector)
            stocks = SECTOR_STOCK_MAP.get(sector, [])
            if stocks:
                result.append((sector, stocks))
    return result


def get_top_stocks_for_text(text, max_total=20, min_weight=4):
    """
    输入一段文本（新闻标题/摘要），输出可能被影响的 top 股票
    按 weight 降序，最多 max_total 只，过滤掉 min_weight 以下的"概念股"

    返回: [(code, name, sector, weight), ...]
    """
    sectors = find_sectors_by_keyword(text)
    pool = []
    for sector, stocks in sectors:
        for code, name, weight in stocks:
            pool.append((code, name, sector, weight))

    # 去重 (同一只股可能跨多个关键词出现)
    seen = set()
    unique = []
    for code, name, sector, weight in pool:
        if code not in seen:
            seen.add(code)
            unique.append((code, name, sector, weight))

    # 按 weight 降序，过滤低 weight
    unique.sort(key=lambda x: -x[3])
    return [x for x in unique if x[3] >= min_weight][:max_total]


